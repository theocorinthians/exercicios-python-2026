n1 = int(input("digite primeiro numero "))
n2 = int(input("digite segundo numero "))

operacao = input(" digite operacao ")
if (operacao == "soma"):
    print (n1 + n2)

elif (operacao == "subtracao"):
    print (n1 - n2)

elif (operacao == "divisao"):
    print (n1 * n2)

elif (operacao == "multiplicasao"):
    print (n1 / n2)